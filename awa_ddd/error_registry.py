def require_validator_code(family: str, name: str) -> str:
    """Return a registered ``v2_<name>`` code or fail closed."""
    if family not in DYNAMIC_ERROR_FAMILIES or not isinstance(name, str):
        raise ValueError("unknown domain validator family")
    code = "v2_" + name
    if not name or code not in DYNAMIC_ERROR_FAMILIES[family]:
        raise ValueError("unregistered domain validator code")
    return code


