"""Central registry of stable AWA-DDD error and validation codes.

The publication layer historically maintained its accepted error names as
three ``_ERROR_CODES`` unions.  This module also accounts for exception
constructors, persisted ``error_code``/guard values, and the ``v2_*`` codes
generated by the domain validation helpers.  It is data-only: importing it
does not inspect a project, execute a scan, or perform any I/O.
"""
from __future__ import annotations

from typing import Final


def _words(value: str) -> frozenset[str]:
    return frozenset(value.split())


def _v2_codes(value: str) -> frozenset[str]:
    return frozenset("v2_" + name for name in value.split())


